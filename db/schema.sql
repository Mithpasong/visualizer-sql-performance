-- Online store sample schema
-- Some columns are intentionally left without an index so performance can be compared.
--   Indexed:     users.email (UNIQUE), products.category_id, orders.user_id, orders.ordered_at,
--                order_items.order_id, reviews.product_id
--   Not indexed: users.name, users.city, orders.status, order_items.product_id, reviews.user_id

DROP TABLE IF EXISTS reviews, order_items, orders, products, categories, users CASCADE;

CREATE TABLE users (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text        NOT NULL UNIQUE,
  name        text        NOT NULL,
  city        text        NOT NULL,
  grade       text        NOT NULL, -- BRONZE / SILVER / GOLD / VIP
  created_at  timestamptz NOT NULL
);

CREATE TABLE categories (
  id         int  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id  int  REFERENCES categories (id),
  name       text NOT NULL
);

CREATE TABLE products (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  int         NOT NULL REFERENCES categories (id),
  name         text        NOT NULL,
  price        int         NOT NULL,
  stock        int         NOT NULL,
  created_at   timestamptz NOT NULL
);

CREATE TABLE orders (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       bigint      NOT NULL REFERENCES users (id),
  status        text        NOT NULL, -- PENDING / PAID / SHIPPED / DELIVERED / CANCELLED
  total_amount  int         NOT NULL DEFAULT 0,
  ordered_at    timestamptz NOT NULL
);

CREATE TABLE order_items (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    bigint NOT NULL REFERENCES orders (id),
  product_id  bigint NOT NULL REFERENCES products (id),
  quantity    int    NOT NULL,
  unit_price  int    NOT NULL
);

CREATE TABLE reviews (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  bigint      NOT NULL REFERENCES products (id),
  user_id     bigint      NOT NULL REFERENCES users (id),
  rating      smallint    NOT NULL CHECK (rating BETWEEN 1 AND 5),
  content     text        NOT NULL,
  created_at  timestamptz NOT NULL
);

CREATE INDEX idx_products_category_id  ON products (category_id);
CREATE INDEX idx_orders_user_id        ON orders (user_id);
CREATE INDEX idx_orders_ordered_at     ON orders (ordered_at);
CREATE INDEX idx_order_items_order_id  ON order_items (order_id);
CREATE INDEX idx_reviews_product_id    ON reviews (product_id);
